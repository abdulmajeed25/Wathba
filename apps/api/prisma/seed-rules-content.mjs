async function main() {
  let created = 0;
  let updated = 0;
  let untouched = 0;

  for (const page of PAGES) {
    const existing = await prisma.editorialCard.findUnique({ where: { slug: page.slug } });

    if (!existing) {
      await prisma.editorialCard.create({ data: { kind: 'RULE', isActive: true, ...page } });
      created++;
      continue;
    }

    const same =
      existing.titleAr === page.titleAr &&
      existing.bodyAr === page.bodyAr &&
      existing.bodyLongAr === page.bodyLongAr &&
      existing.sortOrder === page.sortOrder;

    if (same) {
      untouched++;
      continue;
    }

    // An ops edit through the console is a deliberate act. Overwriting it from a
    // seed would make the console a lie, so a changed row is left alone unless
    // --force says otherwise.
    if (!FORCE) {
      console.warn(`[rules] ${page.slug} differs from this seed — left as is (use --force to overwrite)`);
      untouched++;
      continue;
    }
    await prisma.editorialCard.update({ where: { slug: page.slug }, data: { kind: 'RULE', isActive: true, ...page } });
    updated++;
  }

  console.log(`[rules] ${PAGES.length} page(s): ${created} created, ${updated} rewritten, ${untouched} unchanged`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
